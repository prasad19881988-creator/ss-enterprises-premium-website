/* ---------------------------------------------------------
   Translation function
   --------------------------------------------------------- */

function t(text=""){
  if(currentLang !== "hi") return text;

  const value=String(text);

  if(I18N[value] !== undefined){
    return I18N[value];
  }

  return value;
}


/* ---------------------------------------------------------
   Role / Status translation
   --------------------------------------------------------- */

function translateRole(role=""){
  return t(role);
}

function translateStatus(status=""){
  const value =
    status==="ongoing" || status==="active"
      ? "Ongoing"
      : status==="upcoming"
        ? "Upcoming"
        : "Completed";

  return t(value);
}


