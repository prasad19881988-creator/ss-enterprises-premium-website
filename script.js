function autoTranslate(text=""){
  if(currentLang !== "hi") return text;

  const original=String(text);

  if(I18N[original] !== undefined){
    return I18N[original];
  }

  let result=original;

  AUTO_TRANSLATIONS.forEach(([en,hi])=>{
    result=result.replace(
      new RegExp(`\\b${en.replace(/[.*+?^${}()|[\]\\]/g,"\\$&")}\\b`,"gi"),
      hi
    );
  });

  return result;
}


